//! PostgreSQL schema 同步纯逻辑单元测试（不连接数据库）。

use super::super::dialect::SchemaDialect;
use super::super::plan_table_sync_with;
use super::super::{ExistingIndex, ExistingTableSchema, SchemaSyncChangeKind};
use crate::error::BaseError;
use crate::table::{Field, SchemaColumn, Table, TableDefinition};

fn account_table() -> TableDefinition {
    Table::new("pg_accounts")
        .fields([
            Field::id("id"),
            Field::string("username", 32).required().unique(),
        ])
        .build()
        .expect("pg_accounts 表定义应有效")
}

fn account_table_with_default() -> TableDefinition {
    Table::new("pg_accounts")
        .fields([
            Field::id("id"),
            Field::string("username", 32)
                .required()
                .unique()
                .default("guest"),
        ])
        .build()
        .expect("pg_accounts 表定义应有效")
}

#[test]
fn create_table_uses_postgres_dialect_without_engine_or_inline_key() {
    let table = account_table();
    let plan = plan_table_sync_with(
        SchemaDialect::PostgreSql,
        &table,
        &ExistingTableSchema::missing(),
    )
    .expect("新表应生成 PostgreSQL 建表计划");

    assert_eq!(plan.changes.len(), 1);
    assert_eq!(plan.changes[0].kind, SchemaSyncChangeKind::CreatedTable);
    let create = &plan.statements[0];
    assert!(create.starts_with("CREATE TABLE \"pg_accounts\""));
    assert!(!create.contains("ENGINE"));
    assert!(!create.contains("UNIQUE KEY"));
    assert!(!create.contains(", KEY"));
    assert!(create.contains("\"id\" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY"));
    assert!(create.contains("PRIMARY KEY (\"id\")"));
    assert!(
        plan.statements
            .iter()
            .any(|statement| statement.contains("CREATE UNIQUE INDEX \"uk_pg_accounts_username\"")),
        "PostgreSQL 索引必须独立创建: {:?}",
        plan.statements
    );
}

#[test]
fn modify_column_renders_type_null_and_default_statements() {
    let existing = ExistingTableSchema::existing(
        vec![
            SchemaColumn::new("id", "bigint", "bigint auto_increment", false, None, None),
            SchemaColumn::new("username", "varchar", "varchar(8)", true, Some(8), None),
        ],
        vec!["id".to_string()],
        vec![ExistingIndex::new(
            "uk_pg_accounts_username",
            true,
            vec!["username".to_string()],
        )],
    );
    let plan = plan_table_sync_with(
        SchemaDialect::PostgreSql,
        &account_table_with_default(),
        &existing,
    )
    .expect("受支持的列变更应生成 PostgreSQL 修改计划");

    assert_eq!(plan.changes.len(), 1);
    assert_eq!(plan.changes[0].kind, SchemaSyncChangeKind::ModifiedColumn);
    let statements = plan.statements.join("; ");
    assert!(statements.contains(
        "ALTER TABLE \"pg_accounts\" ALTER COLUMN \"username\" TYPE VARCHAR(32) \
         USING \"username\"::VARCHAR(32)"
    ));
    assert!(statements.contains("ALTER COLUMN \"username\" SET NOT NULL"));
    assert!(statements.contains("ALTER COLUMN \"username\" SET DEFAULT 'guest'"));
}

#[test]
fn compatible_identity_and_postgres_default_are_noop() {
    let existing = ExistingTableSchema::existing(
        vec![
            SchemaColumn::new("id", "bigint", "bigint auto_increment", false, None, None),
            SchemaColumn::new(
                "username",
                "varchar",
                "varchar(32)",
                false,
                Some(32),
                Some("'guest'::character varying".to_string()),
            ),
        ],
        vec!["id".to_string()],
        vec![ExistingIndex::new(
            "uk_pg_accounts_username",
            true,
            vec!["username".to_string()],
        )],
    );

    let plan = plan_table_sync_with(
        SchemaDialect::PostgreSql,
        &account_table_with_default(),
        &existing,
    )
    .expect("identity 与 PG 默认值写法不应被视为漂移");
    assert!(plan.changes.is_empty());
}

#[test]
fn postgres_check_normalization_handles_casts_any_array_and_literals() {
    let dialect = SchemaDialect::PostgreSql;
    assert_eq!(
        dialect.normalize_check_expression("CHECK ((schema_version >= 0))"),
        dialect.normalize_check_expression("\"schema_version\" >= 0")
    );
    assert_eq!(
        dialect.normalize_check_expression(
            "CHECK (((status)::text = ANY ((ARRAY['active'::text, 'disabled'::text]))))"
        ),
        dialect.normalize_check_expression("\"status\" IN ('active', 'disabled')")
    );
    // 字符串字面量内容必须保留，空格差异不能被归一。
    assert_ne!(
        dialect.normalize_check_expression("\"a\" <> ' '"),
        dialect.normalize_check_expression("\"a\" <> ''")
    );
}

#[test]
fn index_name_longer_than_63_bytes_is_rejected() {
    let long_name = "i".repeat(64);
    let table = Table::new("pg_long_index")
        .fields([Field::id("id"), Field::string("username", 32)])
        .index_named(long_name, ["username"])
        .build()
        .expect("测试表定义应有效");

    let error = plan_table_sync_with(
        SchemaDialect::PostgreSql,
        &table,
        &ExistingTableSchema::missing(),
    )
    .expect_err("超过 63 字节的索引名必须拒绝");
    assert!(matches!(error, BaseError::ConfigError(message) if message.contains("63")));
}

#[test]
fn enum_columns_fail_closed_on_postgres() {
    let table = Table::new("pg_enum_unsupported")
        .fields([
            Field::id("id"),
            Field::enumeration("status", ["active", "disabled"]).required(),
        ])
        .build()
        .expect("枚举表定义应有效");

    let error = plan_table_sync_with(
        SchemaDialect::PostgreSql,
        &table,
        &ExistingTableSchema::missing(),
    )
    .expect_err("PostgreSQL 枚举字段必须 fail-closed");
    assert!(matches!(error, BaseError::ConfigError(message) if message.contains("枚举")));
}
