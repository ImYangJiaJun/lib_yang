#[test]
fn create_table_uses_postgres_dialect_without_engine_or_inline_key() {
    let table = account_table();
    let plan = plan_table_sync_with(
        SchemaDialect::PostgreSql,
        &table,
        &ExistingTableSchema::missing(),
    )
    .expect("新表应生成 PostgreSQL 建表计划");

    assert_eq!(plan.changes.len(), 1);
    assert_eq!(plan.changes[0].kind, SchemaSyncChangeKind::CreatedTable);
    let create = &plan.statements[0];
    assert!(create.starts_with("CREATE TABLE \"pg_accounts\""));
    assert!(!create.contains("ENGINE"));
    assert!(!create.contains("UNIQUE KEY"));
    assert!(!create.contains(", KEY"));
    assert!(create.contains("\"id\" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY"));
    assert!(create.contains("PRIMARY KEY (\"id\")"));
    assert!(
        plan.statements
            .iter()
            .any(|statement| statement.contains("CREATE UNIQUE INDEX \"uk_pg_accounts_username\"")),
        "PostgreSQL 索引必须独立创建: {:?}",
        plan.statements
    );
}

